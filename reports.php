<?php
session_start();
require 'dbconnect.php';

// Admin authentication check
if (!isset($_SESSION['admin_logged_in']) || $_SESSION['admin_logged_in'] !== true) {
    header("Location: admin_login.php");
    exit;
}


// Initialize the selected date to an empty string
$selectedDate = '';

// Check if a specific date is selected
if (isset($_POST['selectedDate']) && !empty($_POST['selectedDate'])) {
    $selectedDate = $_POST['selectedDate'];
    $dateCondition = "WHERE DATE(o.order_date) = :selectedDate";
} else {
    $dateCondition = ""; // No specific date selected, display all orders
}

// Fetch sales data with product details based on the selected date
$salesStmt = $pdo->prepare("SELECT o.order_id, o.order_date, o.status, o.total, p.name as product_name, od.quantity
                             FROM orders o
                             JOIN order_details od ON o.order_id = od.order_id
                             JOIN products p ON od.product_id = p.product_id
                             $dateCondition
                             ORDER BY o.order_date DESC");

// If a specific date is selected, bind the parameter
if (!empty($selectedDate)) {
    $salesStmt->bindParam(':selectedDate', $selectedDate);
}

$salesStmt->execute();
$salesData = $salesStmt->fetchAll();
